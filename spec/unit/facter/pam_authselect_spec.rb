# frozen_string_literal: true

require 'spec_helper'
require 'facter'
require 'facter/pam_authselect'

describe :pam_authselect, type: :fact do
  subject(:fact) { Facter.fact(:pam_authselect) }

  let(:conf_file) { '/etc/authselect/authselect.conf' }

  # path => symlink target, or nil for a regular file
  let(:pam_d) do
    {
      '/etc/pam.d/fingerprint-auth' => '/etc/authselect/fingerprint-auth',
      '/etc/pam.d/password-auth'    => '/etc/authselect/password-auth',
      '/etc/pam.d/postlogin'        => '/etc/authselect/postlogin',
      '/etc/pam.d/smartcard-auth'   => '/etc/authselect/smartcard-auth',
      '/etc/pam.d/system-auth'      => '/etc/authselect/system-auth',
      '/etc/pam.d/sshd'             => nil,
      '/etc/pam.d/other'            => '/usr/share/doc/other',
    }
  end

  let(:conf_content) { "minimal\nwith-faillock\nwith-silent-lastlog\n" }

  before :each do
    Facter.clear

    allow(Facter.fact(:kernel)).to receive(:value).and_return('Linux')
    allow(File).to receive(:directory?).and_call_original
    allow(File).to receive(:directory?).with('/etc/authselect').and_return(true)
    allow(File).to receive(:exist?).and_call_original
    allow(File).to receive(:exist?).with(conf_file).and_return(!conf_content.nil?)
    allow(File).to receive(:readlines).and_call_original
    allow(File).to receive(:readlines).with(conf_file).and_return(conf_content.to_s.lines)
    allow(Dir).to receive(:glob).and_call_original
    allow(Dir).to receive(:glob).with('/etc/pam.d/*').and_return(pam_d.keys)
    allow(File).to receive(:symlink?).and_call_original
    allow(File).to receive(:readlink).and_call_original
    pam_d.each do |path, target|
      allow(File).to receive(:symlink?).with(path).and_return(!target.nil?)
      allow(File).to receive(:readlink).with(path).and_return(target) if target
    end
  end

  context 'with a selected profile and authselect symlinks' do
    it do
      expect(fact.value).to eq(
        {
          'profile'   => 'minimal',
          'features'  => ['with-faillock', 'with-silent-lastlog'],
          'symlinked' => ['fingerprint-auth', 'password-auth', 'postlogin', 'smartcard-auth', 'system-auth'],
        },
      )
    end
  end

  context 'with relative symlink targets' do
    let(:pam_d) { { '/etc/pam.d/system-auth' => '../authselect/system-auth' } }

    it { expect(fact.value['symlinked']).to eq(['system-auth']) }
  end

  context 'with a selected profile whose symlinks were replaced by regular files' do
    let(:pam_d) { { '/etc/pam.d/system-auth' => nil, '/etc/pam.d/password-auth' => nil } }

    it { expect(fact.value).to include('profile' => 'minimal', 'symlinked' => []) }
  end

  context 'with comments and blank lines in authselect.conf' do
    let(:conf_content) { "# Generated by authselect\n\nsssd\n\nwith-mkhomedir\n" }

    it { expect(fact.value).to include('profile' => 'sssd', 'features' => ['with-mkhomedir']) }
  end

  context 'with no profile selected and no authselect symlinks' do
    let(:conf_content) { nil }
    let(:pam_d) { { '/etc/pam.d/system-auth' => nil } }

    it { expect(fact.value).to be_nil }
  end

  context 'without /etc/authselect' do
    before :each do
      allow(File).to receive(:directory?).with('/etc/authselect').and_return(false)
    end

    it { expect(fact.value).to be_nil }
  end
end
